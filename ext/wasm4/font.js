const FONT_FIRST = 0x20, FONT_LAST = 0x5f, FONT_BASE = 0xdc00;

// Pack to (FONT_LAST-FONT_FIRST+1)×8 bytes, MSB-first per row (column 0 = bit 7).
// Undefined codepoints → blank glyph. Shared by build.js (→ baked base64) and
// the test (→ written into memory before driving text()).
function packFont() {
  const n = FONT_LAST - FONT_FIRST + 1;
  const bytes = new Uint8Array(n * 8);
  for (let cp = FONT_FIRST; cp <= FONT_LAST; cp++) {
    const rows = glyphs[String.fromCharCode(cp)] || [];
    const base = (cp - FONT_FIRST) * 8;
    for (let r = 0; r < 8; r++) {
      const s = rows[r] || '';
      let b = 0;
      for (let x = 0; x < 8; x++) if (s[x] === '#') b |= 1 << (7 - x);
      bytes[base + r] = b;
    }
  }
  return bytes;
}

module.exports = { FONT_FIRST, FONT_LAST, FONT_BASE, glyphs, packFont };
