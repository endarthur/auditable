#!/usr/bin/env node
// Bundle ext/abus/src/ into ext/abus/index.js — a single ES module.
// Concat strategy (like the other ext/* builds): strip import/export
// statements, concatenate in dependency order, append an export footer.

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const srcDir = path.join(__dirname, 'src');

// protocol.js first — broker.js and client.js depend on it.
const files = ['protocol.js', 'broker.js', 'client.js'];

const chunks = [];
for (const file of files) {
  let src = fs.readFileSync(path.join(srcDir, file), 'utf8');
  src = src.replace(/^import\s+.*['"].*['"];?\s*$/gm, '');
  src = src.replace(/^import\s*\{[^}]*\}\s*from\s*['"].*['"];?\s*$/gm, '');
  src = src.replace(/^export\s*\{[^}]*\}\s*from\s*['"].*['"];?\s*$/gm, '');
  src = src.replace(/^export\s*\{[^}]*\};?\s*$/gm, '');
  src = src.replace(/^export function /gm, 'function ');
  src = src.replace(/^export async function /gm, 'async function ');
  src = src.replace(/^export const /gm, 'const ');
  src = src.replace(/^export let /gm, 'let ');
  src = src.replace(/^export class /gm, 'class ');
  src = src.replace(/^\n+/, '').replace(/\n+$/, '');
  chunks.push(`// -- ${file} --\n\n${src}`);
}

const header = `// @gcu/abus — D-Bus-shaped coordination bus for Auditable Works
// Auto-generated from ext/abus/src/ — do not edit directly
`;

const footer = `
export {
  connect,
  createBroker,
  AbusError,
  ERR,
  BUS_NAME,
  PROTOCOL_VERSION,
  matchesFilter,
  isValidName,
  isValidPath,
  makeIdGen,
};
`;

const output = header + '\n' + chunks.join('\n\n') + footer;
const outPath = path.join(__dirname, 'index.js');
fs.writeFileSync(outPath, output);
console.log(`Built ${outPath} (${(output.length / 1024).toFixed(1)} KB)`);
